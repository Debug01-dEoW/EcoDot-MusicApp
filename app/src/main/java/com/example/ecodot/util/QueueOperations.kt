package com.example.ecodot.util

import com.example.ecodot.data.local.entities.Track

data class QueueInsertResult(
    val queue: List<Track>,
    val originalQueue: List<Track>,
    val insertedStartIndex: Int,
    val autoGeneratedIds: Set<String>
)

data class QueueRemoveResult(
    val removedIndex: Int,
    val newQueue: List<Track>,
    val newOriginalQueue: List<Track>,
    val newCurrentIndex: Int,
    val nextTrackToActivate: Track?,
    val queueCleared: Boolean,
    val autoGeneratedIds: Set<String>
)

/**
 * Pure deterministic queue manipulation logic for Play Next, Add to Queue (ahead of endless filler),
 * and Remove from Queue. Keeps UI queue, original pre-shuffle queue, and controller order consistent.
 */
object QueueOperations {

    fun resolveSafeCurrentIndex(
        queue: List<Track>,
        currentIndex: Int,
        currentTrackId: String? = null,
        controllerIndex: Int? = null
    ): Int {
        if (queue.isEmpty()) return -1
        if (!currentTrackId.isNullOrBlank()) {
            if (controllerIndex != null && controllerIndex in queue.indices && queue[controllerIndex].id == currentTrackId) {
                return controllerIndex
            }
            if (currentIndex in queue.indices && queue[currentIndex].id == currentTrackId) {
                return currentIndex
            }
            val found = queue.indexOfFirst { it.id == currentTrackId }
            if (found >= 0) return found
        }
        if (controllerIndex != null && controllerIndex in queue.indices) return controllerIndex
        if (currentIndex in queue.indices) return currentIndex
        return 0
    }

    fun insertPlayNext(
        queue: List<Track>,
        originalQueue: List<Track>,
        currentIndex: Int,
        track: Track,
        autoGeneratedIds: Set<String>,
        currentTrackId: String? = null,
        controllerIndex: Int? = null
    ): QueueInsertResult {
        if (queue.isEmpty()) {
            return QueueInsertResult(
                queue = listOf(track),
                originalQueue = listOf(track),
                insertedStartIndex = 0,
                autoGeneratedIds = emptySet()
            )
        }

        val safeIdx = resolveSafeCurrentIndex(queue, currentIndex, currentTrackId, controllerIndex)
        val insertIdx = (safeIdx + 1).coerceIn(0, queue.size)
        val mutableQueue = queue.toMutableList()
        for (i in mutableQueue.lastIndex downTo insertIdx) {
            if (mutableQueue[i].id == track.id) {
                mutableQueue.removeAt(i)
            }
        }
        val clampedInsert = insertIdx.coerceIn(0, mutableQueue.size)
        mutableQueue.add(clampedInsert, track)

        val activeId = queue.getOrNull(safeIdx)?.id ?: currentTrackId
        val mutableOrig = originalQueue.ifEmpty { queue }.toMutableList()
        val origActiveIdx = if (!activeId.isNullOrBlank()) mutableOrig.indexOfFirst { it.id == activeId } else -1
        val origInsertBase = if (origActiveIdx != -1) origActiveIdx + 1 else mutableOrig.size
        for (i in mutableOrig.lastIndex downTo origInsertBase.coerceAtMost(mutableOrig.size)) {
            if (mutableOrig[i].id == track.id) {
                mutableOrig.removeAt(i)
            }
        }
        mutableOrig.add(origInsertBase.coerceIn(0, mutableOrig.size), track)

        return QueueInsertResult(
            queue = mutableQueue,
            originalQueue = mutableOrig,
            insertedStartIndex = clampedInsert,
            autoGeneratedIds = autoGeneratedIds - track.id
        )
    }

    fun insertAddToQueue(
        queue: List<Track>,
        originalQueue: List<Track>,
        currentIndex: Int,
        tracksToAdd: List<Track>,
        autoGeneratedIds: Set<String>,
        currentTrackId: String? = null,
        controllerIndex: Int? = null
    ): QueueInsertResult {
        val distinctAdd = tracksToAdd.distinctBy { it.id }
        if (distinctAdd.isEmpty()) {
            return QueueInsertResult(queue, originalQueue, -1, autoGeneratedIds)
        }
        if (queue.isEmpty()) {
            return QueueInsertResult(
                queue = distinctAdd,
                originalQueue = distinctAdd,
                insertedStartIndex = 0,
                autoGeneratedIds = emptySet()
            )
        }

        val safeIdx = resolveSafeCurrentIndex(queue, currentIndex, currentTrackId, controllerIndex)
        val addedIds = distinctAdd.map { it.id }.toSet()
        val mutableQueue = queue.toMutableList()

        // Find where auto-generated Endless Queue tracks start in the upcoming slice.
        val upcomingStart = (safeIdx + 1).coerceIn(0, mutableQueue.size)
        var userQueueEnd = (upcomingStart until mutableQueue.size)
            .firstOrNull { mutableQueue[it].id in autoGeneratedIds }
            ?: mutableQueue.size

        // Remove any upcoming duplicate of tracks being queued so they appear in order at userQueueEnd.
        for (i in mutableQueue.lastIndex downTo upcomingStart) {
            if (mutableQueue[i].id in addedIds) {
                mutableQueue.removeAt(i)
                if (i < userQueueEnd) userQueueEnd--
            }
        }
        val insertIdx = userQueueEnd.coerceIn(upcomingStart, mutableQueue.size)
        mutableQueue.addAll(insertIdx, distinctAdd)

        val activeId = queue.getOrNull(safeIdx)?.id ?: currentTrackId
        val mutableOrig = originalQueue.ifEmpty { queue }.toMutableList()
        val origActiveIdx = if (!activeId.isNullOrBlank()) mutableOrig.indexOfFirst { it.id == activeId } else -1
        val origUpcomingStart = if (origActiveIdx != -1) (origActiveIdx + 1).coerceIn(0, mutableOrig.size) else mutableOrig.size
        var origUserEnd = (origUpcomingStart until mutableOrig.size)
            .firstOrNull { mutableOrig[it].id in autoGeneratedIds }
            ?: mutableOrig.size
        for (i in mutableOrig.lastIndex downTo origUpcomingStart) {
            if (mutableOrig[i].id in addedIds) {
                mutableOrig.removeAt(i)
                if (i < origUserEnd) origUserEnd--
            }
        }
        mutableOrig.addAll(origUserEnd.coerceIn(origUpcomingStart, mutableOrig.size), distinctAdd)

        return QueueInsertResult(
            queue = mutableQueue,
            originalQueue = mutableOrig,
            insertedStartIndex = insertIdx,
            autoGeneratedIds = autoGeneratedIds - addedIds
        )
    }

    fun removeTrack(
        queue: List<Track>,
        originalQueue: List<Track>,
        currentIndex: Int,
        track: Track,
        preferredIndex: Int? = null,
        autoGeneratedIds: Set<String>,
        currentTrackId: String? = null,
        controllerIndex: Int? = null
    ): QueueRemoveResult? {
        if (queue.isEmpty()) return null
        val safeIdx = resolveSafeCurrentIndex(queue, currentIndex, currentTrackId, controllerIndex)

        val targetIndex = when {
            preferredIndex != null && preferredIndex in queue.indices && queue[preferredIndex].id == track.id ->
                preferredIndex
            else -> {
                val upcomingStart = (safeIdx + 1).coerceIn(0, queue.size)
                (upcomingStart until queue.size).firstOrNull { queue[it].id == track.id }
                    ?: queue.indexOfFirst { it.id == track.id }
            }
        }
        if (targetIndex !in queue.indices) return null

        val mutableQueue = queue.toMutableList()
        mutableQueue.removeAt(targetIndex)

        val mutableOrig = originalQueue.ifEmpty { queue }.toMutableList()
        val origIdx = mutableOrig.indexOfLast { it.id == track.id }
        if (origIdx != -1) mutableOrig.removeAt(origIdx)

        val stillInQueue = mutableQueue.any { it.id == track.id }
        val nextAutoIds = if (stillInQueue) autoGeneratedIds else autoGeneratedIds - track.id

        if (mutableQueue.isEmpty()) {
            return QueueRemoveResult(
                removedIndex = targetIndex,
                newQueue = emptyList(),
                newOriginalQueue = emptyList(),
                newCurrentIndex = -1,
                nextTrackToActivate = null,
                queueCleared = true,
                autoGeneratedIds = emptySet()
            )
        }

        val (newCurrentIdx, nextActive) = when {
            targetIndex < safeIdx -> (safeIdx - 1).coerceIn(0, mutableQueue.lastIndex) to null
            targetIndex > safeIdx -> safeIdx to null
            else -> {
                val clamped = targetIndex.coerceIn(0, mutableQueue.lastIndex)
                clamped to mutableQueue[clamped]
            }
        }

        return QueueRemoveResult(
            removedIndex = targetIndex,
            newQueue = mutableQueue,
            newOriginalQueue = mutableOrig,
            newCurrentIndex = newCurrentIdx,
            nextTrackToActivate = nextActive,
            queueCleared = false,
            autoGeneratedIds = nextAutoIds
        )
    }
}
