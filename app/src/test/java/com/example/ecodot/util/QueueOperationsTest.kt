package com.example.ecodot.util

import com.example.ecodot.data.local.entities.Track
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class QueueOperationsTest {

    private fun fakeTrack(id: String, title: String = "Track $id"): Track = Track(
        id = id,
        title = title,
        artist = "Artist $id",
        album = "Album",
        duration = 180_000L,
        path = "yt://$id",
        isYouTube = true
    )

    @Test
    fun `insertPlayNext starts queue when empty`() {
        val t1 = fakeTrack("t1")
        val res = QueueOperations.insertPlayNext(
            queue = emptyList(),
            originalQueue = emptyList(),
            currentIndex = -1,
            track = t1,
            autoGeneratedIds = emptySet()
        )
        assertEquals(listOf(t1), res.queue)
        assertEquals(0, res.insertedStartIndex)
    }

    @Test
    fun `insertPlayNext places track immediately after active track and moves upcoming duplicate`() {
        val t1 = fakeTrack("t1")
        val t2 = fakeTrack("t2")
        val t3 = fakeTrack("t3")
        val r1 = fakeTrack("r1")

        val res = QueueOperations.insertPlayNext(
            queue = listOf(t1, t2, t3, r1),
            originalQueue = listOf(t1, t2, t3, r1),
            currentIndex = 0,
            track = t3,
            autoGeneratedIds = setOf("r1"),
            currentTrackId = "t1",
            controllerIndex = 0
        )

        assertEquals(listOf("t1", "t3", "t2", "r1"), res.queue.map { it.id })
        assertEquals(1, res.insertedStartIndex)
    }

    @Test
    fun `insertPlayNext on currently playing track queues replay right next without removing current`() {
        val t1 = fakeTrack("t1")
        val t2 = fakeTrack("t2")

        val res = QueueOperations.insertPlayNext(
            queue = listOf(t1, t2),
            originalQueue = listOf(t1, t2),
            currentIndex = 0,
            track = t1,
            autoGeneratedIds = emptySet(),
            currentTrackId = "t1"
        )

        assertEquals(listOf("t1", "t1", "t2"), res.queue.map { it.id })
        assertEquals(1, res.insertedStartIndex)
    }

    @Test
    fun `insertAddToQueue inserts before autoGenerated endless radio tracks and promotes radio track`() {
        val playing = fakeTrack("p")
        val manualNext = fakeTrack("m1")
        val radio1 = fakeTrack("r1")
        val radio2 = fakeTrack("r2")
        val userQueued = fakeTrack("u1")

        val res = QueueOperations.insertAddToQueue(
            queue = listOf(playing, manualNext, radio1, radio2),
            originalQueue = listOf(playing, manualNext, radio1, radio2),
            currentIndex = 0,
            tracksToAdd = listOf(userQueued, radio2),
            autoGeneratedIds = setOf("r1", "r2"),
            currentTrackId = "p"
        )

        // Manual queue grows right after manualNext and strictly BEFORE auto-generated radio1
        assertEquals(listOf("p", "m1", "u1", "r2", "r1"), res.queue.map { it.id })
        assertEquals(setOf("r1"), res.autoGeneratedIds)
    }

    @Test
    fun `removeTrack removes upcoming item and preserves active track`() {
        val t1 = fakeTrack("t1")
        val t2 = fakeTrack("t2")
        val t3 = fakeTrack("t3")

        val res = QueueOperations.removeTrack(
            queue = listOf(t1, t2, t3),
            originalQueue = listOf(t1, t2, t3),
            currentIndex = 0,
            track = t2,
            preferredIndex = 1,
            autoGeneratedIds = emptySet(),
            currentTrackId = "t1"
        )

        assertNotNull(res)
        assertEquals(1, res!!.removedIndex)
        assertEquals(listOf("t1", "t3"), res.newQueue.map { it.id })
        assertEquals(0, res.newCurrentIndex)
        assertNull(res.nextTrackToActivate)
    }

    @Test
    fun `removeTrack on currently active item advances to next or clears when sole track`() {
        val t1 = fakeTrack("t1")
        val t2 = fakeTrack("t2")

        val advanceRes = QueueOperations.removeTrack(
            queue = listOf(t1, t2),
            originalQueue = listOf(t1, t2),
            currentIndex = 0,
            track = t1,
            autoGeneratedIds = emptySet(),
            currentTrackId = "t1"
        )
        assertNotNull(advanceRes)
        assertEquals("t2", advanceRes!!.nextTrackToActivate?.id)
        assertEquals(0, advanceRes.newCurrentIndex)

        val clearRes = QueueOperations.removeTrack(
            queue = listOf(t1),
            originalQueue = listOf(t1),
            currentIndex = 0,
            track = t1,
            autoGeneratedIds = emptySet(),
            currentTrackId = "t1"
        )
        assertNotNull(clearRes)
        assertTrue(clearRes!!.queueCleared)
        assertEquals(-1, clearRes.newCurrentIndex)
    }
}
